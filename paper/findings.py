"""The headline results, built from the generated summaries; never typed by hand.

Used by build_paper.py (the results strip in the web reader) and to write the "What it found"
block in README.md between the findings markers. tests/test_generated_files.py fails when the
README block is stale. Run: uv run --frozen python paper/findings.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

PAPER = Path(__file__).resolve().parent
ROOT = PAPER.parent
README = ROOT / "README.md"
START = "<!-- findings:start (generated by paper/findings.py; do not edit) -->"
END = "<!-- findings:end -->"
SOURCES = {
    "corpus": ROOT / "corpus" / "data" / "summary.json",
    "bench": ROOT / "bench" / "results" / "summary.json",
    "rq3": ROOT / "bench" / "results" / "rq3.json",
    "dogfood": PAPER / "data" / "dogfood_audit.json",
}
TAGS = {"pos": "holds", "null": "null", "find": "finding"}

Row = tuple[str, str, str, str]


def load(path: Path) -> dict[str, Any]:
    data: dict[str, Any] = json.loads(path.read_text(encoding="utf-8"))
    return data


def _pct(x: float) -> str:
    return f"{100 * x:.1f}%"


def _p(v: float | None) -> str:
    if v is None:
        return "n/a"
    return "< 0.001" if v < 0.001 else f"{v:.3f}"


def rows() -> list[Row]:
    """(id, kind, statement, detail) per result; kind is pos, null or find."""
    corpus, bench, rq3, dog = (load(SOURCES[k]) for k in ("corpus", "bench", "rq3", "dogfood"))
    m = corpus["model"]
    out: list[Row] = [
        (
            "RQ1",
            "find",
            "A minority of instruction-file rules are decidable on a diff: "
            f"{_pct(m['decidability_p1']['deterministic']['share'])} (model) to "
            f"{_pct(corpus['rubric_decidability']['deterministic']['share'])} (rubric).",
            f"{corpus['n_lines']:,} lines from {corpus['n_files']} files; both labellers agree on "
            f"{_pct(m['rubric_model_agreement']['deterministic_by_both_share_of_all'])}; "
            f"κ = {m['kappa_rubric_p1_decidability']:.2f}",
        )
    ]
    h1 = bench["H1_viol_det_B_C"]
    out.append(
        (
            "H1",
            "null",
            "Hooks (C) vs rules in CLAUDE.md (B): final-diff violations.",
            f"ceiling: mean {h1['mean_B']:g} vs {h1['mean_C']:g}; p = {_p(h1['p'])}, n = {h1['n_tasks']} tasks",
        )
    )
    sec = bench["secondary"]
    out.append(
        (
            "H2",
            "null",
            "Rules in CLAUDE.md (B) vs no rules (A): final-diff violations.",
            f"ceiling in both; p_Holm = {_p(sec['H2_viol_det_A_B']['p_holm'])}",
        )
    )
    out.append(
        (
            "H3",
            "null",
            "Heuristic-tier violations, C vs B.",
            f"p_Holm = {_p(sec['H3_viol_heur_B_C']['p_holm'])}",
        )
    )
    h4 = bench["H4_success_B_C"]
    out.append(
        (
            "H4",
            "pos" if h4["non_inferior"] else "null",
            "Task success with hooks is non-inferior (margin −10 pp).",
            f"{_pct(h4['rate_C'])} vs {_pct(h4['rate_B'])}; diff CI {_pct(h4['ci95'][0])} to {_pct(h4['ci95'][1])}",
        )
    )
    cost = ("H5_turns_B_C", "H5_tokens_B_C", "H5_wall_s_B_C")
    out.append(
        (
            "H5",
            "null",
            "Cost of the hooks (turns, tokens, wall-clock), C vs B.",
            f"median +{sec['H5_turns_B_C']['median_diff']:.2f} turns, "
            f"+{sec['H5_wall_s_B_C']['median_diff']:.1f} s; "
            f"p_Holm ≥ {_p(min(sec[k]['p_holm'] for k in cost))}",
        )
    )
    out.append(
        (
            "H6",
            "null",
            "Managed (C) vs flat (D) reports: cycles to a clean state.",
            f"p_Holm = {_p(sec['H6_cycles_C_D']['p_holm'])}",
        )
    )
    props = rq3["safety_properties"].values()
    tests, passed = sum(v["tests"] for v in props), sum(v["passed"] for v in props)
    pre = bench["RQ3_hook_latency_ms"]["PreToolUse"]
    out.append(
        (
            "RQ3",
            "pos" if tests == passed else "null",
            f"{passed}/{tests} determinism and fail-closed tests pass.",
            f"PreToolUse median {pre['p50']} ms, p99 {pre['p99']} ms in real runs",
        )
    )
    q5 = bench["RQ5"]
    out.append(
        (
            "RQ5",
            "null",
            "Circumvention attempts under an adversarial prompt.",
            f"{q5['attempts']} attempts in {q5['runs']} runs",
        )
    )
    br = bench["blocks_by_rule"]["C"]
    out.append(
        (
            "Hooks",
            "find",
            "What the hooks caught mid-session in condition C.",
            f"{br.get('B-DOCSTRING', 0)} genuine denials, all self-corrected; "
            f"{br.get('B-TESTS-RO', 0)} false positives from a defect, since fixed",
        )
    )
    out.append(
        (
            "Dogfood",
            "find",
            "rulewarden enforced its own repository during development.",
            f"{dog['chain']['entries']} audited decisions, "
            f"{dog['by_status'].get('blocked', 0)} blocking; chain {dog['chain']['message']}",
        )
    )
    return out


def readme_block() -> str:
    """The Markdown between the README markers, markers included."""
    bench = load(SOURCES["bench"])
    lines = [
        START,
        f"Generated from the result files ({bench['n_runs']} benchmark runs). "
        "*null* means no detectable difference; here every condition reached the ceiling.",
        "",
        "| | Result | Detail | Verdict |",
        "|---|---|---|---|",
    ]
    lines += [f"| **{i}** | {s} | {d} | {TAGS[k]} |" for i, k, s, d in rows()]
    return "\n".join([*lines, END])


def update_readme(text: str) -> str:
    head, sep, rest = text.partition(START)
    _, sep2, tail = rest.partition(END)
    if not sep or not sep2:
        raise ValueError("README.md has no findings markers")
    return head + readme_block() + tail


def main() -> int:
    README.write_text(update_readme(README.read_text(encoding="utf-8")), encoding="utf-8")
    sys.stdout.write("updated the findings block in README.md\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
